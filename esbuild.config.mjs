import esbuild from 'esbuild';
import process from 'process';
import { readFile } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import { parse } from 'yaml';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
See the source repository for the original TypeScript.
*/
`;

/**
 * The local API's contract is written as YAML, for the people who read it,
 * and carried in the bundle as the object it describes. It is read here, at
 * build time, so nothing in Obsidian has to parse it and no parser's reading
 * of it can differ from the one the tests were run against.
 */
const yamlAsJson = {
	name: 'yaml-as-json',
	setup(build) {
		build.onLoad({ filter: /\.yaml$/ }, async (args) => ({
			contents: JSON.stringify(parse(await readFile(args.path, 'utf8'))),
			loader: 'json',
		}));
	},
};

const production = process.argv[2] === 'production';
const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	plugins: [yamlAsJson],
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	// The two Node modules the plugin reaches, on the desktop alone, are each
	// asked for with a dynamic import behind `Platform.isDesktop`. Left as it
	// is, the bundle would hand such an import to the page's own loader, which
	// knows no bare module name, so it is lowered to the `require` Obsidian
	// gives a plugin. Nothing else in the bundle is a native import.
	supported: { 'dynamic-import': false },
	jsx: 'automatic',
	// React reads the first to choose its production build, and a library it
	// stands on reads the second, which a CommonJS bundle has no `import.meta`
	// to answer for. Both are said here, where the choice is made.
	define: {
		'process.env.NODE_ENV': JSON.stringify(production ? 'production' : 'development'),
		'import.meta.env': JSON.stringify({ MODE: production ? 'production' : 'development' }),
	},
	logLevel: 'info',
	sourcemap: production ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: production,
});

if (production) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
